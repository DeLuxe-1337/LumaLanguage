    xor eax, eax
    xor r11, r11
    sub rsp, 8
    add rsp, 8
    sub rsp, 256
    add eax, 2
    add rax, rcx
    sub rax, rcx
    lea rdi, [rip + .Lmsg]
    lea rsi, [rip + .Lmsg + 3]
    lea rdx, [rip + counter]
    lea r9, [rip - 4]
    call helper
    call entry
    call puts@PLT
    call external_fn
    nop
    pop r12
    pop rbp
    ret
    .size entry, .-entry
helper:
    ret

