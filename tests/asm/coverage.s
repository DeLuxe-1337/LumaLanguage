    mov rax, [rbp]
    mov r9, [rbp + 16]
    mov [rbp - 16], rdi
    mov [rbp - 16], r9
    mov [rbp - 200], rax
    lea rax, [rbp - 8]
    mov rax, [rip + counter]
    mov [rip + counter], rax
    cmp rax, 2
    cmp rax, 1000
    cmp rcx, 1000
    cmp rax, rcx
    cmp eax, 5
    and rax, -5
    and rdx, rcx
    and rax, 0x1000
    or rax, 1
    or rcx, rdx
    add rax, 0x1000
    sub rax, 0x1000
    xor rax, 0x1000
    test edx, 1
    test eax, 1
    test rax, rcx
    test r10, 0x100
    lea rax, [rip + .Lobj]
